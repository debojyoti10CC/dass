import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';

export function compile({ writeFrontend = true } = {}) {
  const deploymentName = process.env.DASS_DEPLOYMENT ?? 'arc-testnet';
  if (!['arc-testnet', 'arc-mainnet', 'local'].includes(deploymentName)) throw new Error('DASS_DEPLOYMENT must be arc-testnet, arc-mainnet or local');
  const sources = {};
  for (const directory of ['contracts/src', 'contracts/test', 'contracts/script']) {
    if (!fs.existsSync(directory)) continue;
    for (const file of fs.readdirSync(directory).filter(f => f.endsWith('.sol'))) {
      const name = `${directory}/${file}`;
      sources[name] = { content: fs.readFileSync(name, 'utf8') };
    }
  }
  const input = { language: 'Solidity', sources, settings: {
    optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'metadata'] } }
  }};
  const output = JSON.parse(solc.compile(JSON.stringify(input), { import: name => {
    const candidates = [name, path.posix.join('contracts/src', name), path.posix.join('contracts/script', name), path.join('node_modules', name)];
    for (const candidate of candidates) {
      if (fs.existsSync(candidate)) {
        const contents = fs.readFileSync(candidate, 'utf8');
        input.sources[name] = { content: contents };
        return { contents };
      }
    }
    return { error: `Missing import: ${name}` };
  }}));
  const errors = (output.errors ?? []).filter(e => e.severity === 'error');
  if (errors.length) throw new Error(errors.map(e => e.formattedMessage).join('\n'));
  fs.mkdirSync('work/artifacts', { recursive: true });
  fs.writeFileSync('work/artifacts/standard-input.json', JSON.stringify(input));
  const artifacts = {};
  for (const [sourceName, contracts] of Object.entries(output.contracts ?? {})) {
    if (!sourceName.startsWith('contracts/')) continue;
    for (const [contractName, value] of Object.entries(contracts)) {
      const artifact = { contractName, sourceName, compiler: solc.version(), abi: value.abi,
        bytecode: `0x${value.evm.bytecode.object}`, deployedBytecode: `0x${value.evm.deployedBytecode.object}` };
      artifacts[contractName] = artifact;
      fs.writeFileSync(`work/artifacts/${contractName}.json`, JSON.stringify(artifact, null, 2) + '\n');
    }
  }
  if (writeFrontend && artifacts.DistributionMarkets) {
    fs.mkdirSync('web/src', { recursive: true });
    fs.writeFileSync('web/src/contracts.ts', '// Generated by scripts/compile.mjs. Do not edit by hand.\n'
      + `import manifest from '../../deployments/${deploymentName}.json';\n`
      + `export const distributionMarketsAbi = ${JSON.stringify(artifacts.DistributionMarkets.abi, null, 2)} as const;\n`
      + 'export const deployment = manifest as { network: string; chainId: number; address: string | null; deploymentBlock: number | null; tokenAddress: string; rpcUrl: string; explorerUrl: string; status: string; sourceCommit: string | null; verificationUrl: string | null };\n');
  }
  console.log(`Solidity ${solc.version()}: compiled ${Object.keys(artifacts).join(', ')}`);
  return artifacts;
}
if (process.argv[1]?.endsWith('compile.mjs')) compile();
